// ─── Memory facets — the Knows screen's vocabulary ──────────────────────────
// Pure functions only. No database, no `server-only`: the API route, the React
// view, and the tests all import the SAME rules, so "what bucket is this in"
// and "what does the provenance line say" can never drift between them.
//
// Two facets were added to agent_memory in migration 0358:
//
//   category      rooms | people | rhythm | vendors | guests — the five groups
//                 the manager sees. The DATABASE classifies (a trigger calls
//                 staxis_classify_memory_category) so every write path is
//                 covered, including the LLM-authored `remember` tool. The job
//                 HERE is the inverse: coerce a category that came back from a
//                 model or a browser into the valid set, never trusting it.
//
//   review_state  unreviewed | confirmed. Unreviewed = extracted from pasted
//                 text or an uploaded file and not yet approved by a human.
//                 Those rows are excluded from the copilot's per-turn read;
//                 this module only decides how they LOOK.

export const MEMORY_CATEGORIES = ['rooms', 'people', 'rhythm', 'vendors', 'guests'] as const;
export type MemoryCategory = (typeof MEMORY_CATEGORIES)[number];

/**
 * The bucket a fact lands in when nothing else matches. Mirrors the SQL
 * classifier's fallback in 0358 — a fact we can't place is a fact about how
 * this hotel runs. Changing this means changing the migration too.
 */
export const DEFAULT_MEMORY_CATEGORY: MemoryCategory = 'rhythm';

export type MemoryReviewState = 'unreviewed' | 'confirmed';

export function isMemoryCategory(v: unknown): v is MemoryCategory {
  return typeof v === 'string' && (MEMORY_CATEGORIES as readonly string[]).includes(v);
}

/**
 * Coerce an untrusted category (model output, request body, a stale client) to
 * a valid bucket. NEVER throws and never returns null — a bad value becomes the
 * safe default rather than a 500 or a NULL hole.
 */
export function coerceMemoryCategory(v: unknown): MemoryCategory {
  if (typeof v !== 'string') return DEFAULT_MEMORY_CATEGORY;
  const normalized = v.trim().toLowerCase();
  return isMemoryCategory(normalized) ? normalized : DEFAULT_MEMORY_CATEGORY;
}

